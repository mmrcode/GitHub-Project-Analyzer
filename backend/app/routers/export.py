from fastapi import APIRouter
from fastapi.responses import PlainTextResponse, HTMLResponse, JSONResponse
from app.models.schemas import FullRepoAnalysis

router = APIRouter(prefix="/export", tags=["Report Export"])

@router.post("/markdown", response_class=PlainTextResponse)
async def export_markdown_report(analysis: FullRepoAnalysis):
    """Generates a comprehensive Markdown project report."""
    meta = analysis.metadata
    tech = analysis.technology

    tech_table_rows = "\n".join([
        f"| {t.name} | {t.category} | {t.version or 'N/A'} | `{t.source_file}` | {t.description or ''} |"
        for t in tech.technologies
    ]) or "| None | N/A | N/A | N/A | N/A |"

    parsed_files_md = []
    for pf in analysis.parsed_code:
        cls_str = ", ".join([f"`{c.name}`" for c in pf.classes]) or "None"
        fn_str = ", ".join([f"`{f.name}()`" for f in pf.functions[:5]]) or "None"
        entry_tag = " (Entry Point)" if pf.is_entry_point else ""
        parsed_files_md.append(f"- **`{pf.path}`**{entry_tag} - LOC: {pf.loc}\n  - Classes: {cls_str}\n  - Functions: {fn_str}")

    setup_prereqs = "\n".join([f"- {p}" for p in analysis.setup_guide.prerequisites])
    setup_steps_md = "\n".join([
        f"### {step.title}\n{step.description}\n```bash\n{step.command or ''}\n```"
        for step in (analysis.setup_guide.install_steps + analysis.setup_guide.run_steps)
    ])

    viva_md = []
    for q in analysis.viva_questions:
        viva_md.append(
            f"### Q{q.id}. {q.question}\n"
            f"**Category:** {q.category} | **Difficulty:** {q.difficulty}\n\n"
            f"> **Model Answer:** {q.answer_hint}\n"
        )

    ai_sum = analysis.ai_summary
    ai_sec = ""
    if ai_sum:
        features = "\n".join([f"- {f}" for f in ai_sum.key_features])
        patterns = ", ".join(ai_sum.design_patterns)
        ai_sec = f"""
## AI Architecture Overview & Insights
{ai_sum.summary}

### Architecture Breakdown
{ai_sum.architecture_overview}

### Key Implemented Features
{features}

### Design Patterns
{patterns}
"""

    md_content = f"""# Repository Analysis Report: {meta.full_name}

**Generated by GitHub Project Analyzer (MCA Mini Project)**  
**Repository URL:** {meta.html_url}  
**Primary Language:** {tech.primary_language} | **Stars:** {meta.stars} | **Forks:** {meta.forks} | **License:** {meta.license or 'None'}

---

## 1. Project Description
{meta.description or 'No repository description available.'}

{ai_sec}

---

## 2. Technology Stack & Dependencies

| Technology | Category | Version | Declared In | Purpose |
|---|---|---|---|---|
{tech_table_rows}

---

## 3. Codebase Metrics
- **Total Files:** {tech.total_files}
- **Total Directories:** {tech.total_directories}
- **Total Size:** {tech.total_bytes / 1024:.1f} KB
- **Source Files Analyzed:** {len(analysis.parsed_code)}

### Language Distribution
{"".join([f"- **{l.name}**: {l.percentage}% ({l.file_count} files)\n" for l in tech.languages])}

---

## 4. Static Source Code & AST Analysis

{chr(10).join(parsed_files_md)}

---

## 5. Setup & Execution Guide

### Prerequisites
{setup_prereqs}

{setup_steps_md}

---

## 6. MCA Viva Examination Preparation Questions

{chr(10).join(viva_md)}

---
*Report generated automatically using GitHub Project Analyzer Static Analysis Engine & Google Gemini.*
"""
    return md_content.strip()

